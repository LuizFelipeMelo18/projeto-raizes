CREATE TABLE pagamento_evento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pagamento_id BIGINT NOT NULL REFERENCES pagamento (id),
    operacao VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL,
    codigo_mock VARCHAR(40),
    payload TEXT NOT NULL,
    registrado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_pagamento_evento_operacao CHECK (operacao IN ('SOLICITACAO', 'RECONCILIACAO')),
    CONSTRAINT ck_pagamento_evento_status CHECK (status IN ('APROVADO', 'RECUSADO', 'INDETERMINADO'))
);
CREATE INDEX ix_pagamento_evento_pagamento ON pagamento_evento (pagamento_id, registrado_em, id);
