-- Programa de fidelidade: ledger de pontos por cliente, ligado a pedidos.
-- Regra (RegraFidelidade): 1 ponto por R$ 1,00 pago em pedido ENTREGUE; resgate em blocos de 100 pontos = R$ 5,00;
-- desconto limitado a 50% do subtotal dos itens. Pedido anônimo ou sem consentimento não participa.

-- total passa a ser o valor a pagar; subtotal dos itens = total + desconto_fidelidade.
ALTER TABLE pedido
    ADD COLUMN desconto_fidelidade NUMERIC(12, 2) NOT NULL DEFAULT 0,
    ADD COLUMN pontos_resgatados INTEGER NOT NULL DEFAULT 0,
    ADD COLUMN participa_fidelidade BOOLEAN NOT NULL DEFAULT FALSE;

ALTER TABLE pedido ADD CONSTRAINT ck_pedido_fidelidade CHECK (
    desconto_fidelidade >= 0
    AND pontos_resgatados >= 0
    AND MOD(pontos_resgatados, 100) = 0
    AND (pontos_resgatados = 0) = (desconto_fidelidade = 0)
    AND (participa_fidelidade OR pontos_resgatados = 0)
    AND (cliente_id IS NOT NULL OR NOT participa_fidelidade)
);

CREATE TABLE fidelidade_conta (
    usuario_id BIGINT PRIMARY KEY REFERENCES usuario (id),
    saldo INTEGER NOT NULL DEFAULT 0,
    versao BIGINT NOT NULL DEFAULT 0,
    atualizado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_fidelidade_conta_saldo CHECK (saldo >= 0)
);

CREATE TABLE fidelidade_movimento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES fidelidade_conta (usuario_id),
    pedido_id BIGINT NOT NULL REFERENCES pedido (id),
    ator_id BIGINT REFERENCES usuario (id),
    tipo VARCHAR(20) NOT NULL,
    pontos INTEGER NOT NULL,
    saldo_apos INTEGER NOT NULL,
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_fidelidade_movimento_tipo CHECK (tipo IN ('ACUMULO', 'RESGATE', 'ESTORNO_RESGATE')),
    CONSTRAINT ck_fidelidade_movimento_valores CHECK (pontos > 0 AND saldo_apos >= 0),
    -- Um crédito, um resgate e um estorno no máximo por pedido: entrega reprocessada não credita duas vezes.
    CONSTRAINT uq_fidelidade_movimento_pedido_tipo UNIQUE (pedido_id, tipo)
);

CREATE INDEX ix_fidelidade_movimento_usuario_criado
    ON fidelidade_movimento (usuario_id, criado_em DESC, id DESC);

