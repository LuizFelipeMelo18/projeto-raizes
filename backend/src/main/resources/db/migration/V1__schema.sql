CREATE TABLE unidade (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    ativa BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unidade_id BIGINT REFERENCES unidade (id),
    nome VARCHAR(120) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    senha_hash VARCHAR(100) NOT NULL,
    perfil VARCHAR(20) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_usuario_perfil CHECK (perfil IN ('CLIENTE', 'TOTEM', 'ATENDENTE', 'COZINHA', 'GERENTE')),
    CONSTRAINT ck_usuario_unidade CHECK (
        (perfil = 'CLIENTE' AND unidade_id IS NULL)
        OR (perfil <> 'CLIENTE' AND unidade_id IS NOT NULL)
    )
);

CREATE TABLE produto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE cardapio_item (
    unidade_id BIGINT NOT NULL REFERENCES unidade (id),
    produto_id BIGINT NOT NULL REFERENCES produto (id),
    preco NUMERIC(12, 2) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    PRIMARY KEY (unidade_id, produto_id),
    CONSTRAINT ck_cardapio_preco CHECK (preco > 0)
);

CREATE TABLE estoque_saldo (
    unidade_id BIGINT NOT NULL,
    produto_id BIGINT NOT NULL,
    fisico INTEGER NOT NULL DEFAULT 0,
    reservado INTEGER NOT NULL DEFAULT 0,
    versao BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (unidade_id, produto_id),
    FOREIGN KEY (unidade_id, produto_id) REFERENCES cardapio_item (unidade_id, produto_id),
    CONSTRAINT ck_estoque_saldo CHECK (fisico >= 0 AND reservado >= 0 AND reservado <= fisico)
);

CREATE TABLE pedido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unidade_id BIGINT NOT NULL REFERENCES unidade (id),
    cliente_id BIGINT REFERENCES usuario (id),
    criado_por_id BIGINT NOT NULL REFERENCES usuario (id),
    canal_pedido VARCHAR(20) NOT NULL,
    modalidade_atendimento VARCHAR(20) NOT NULL,
    status VARCHAR(30) NOT NULL,
    forma_pagamento VARCHAR(20) NOT NULL,
    total NUMERIC(12, 2) NOT NULL,
    versao BIGINT NOT NULL DEFAULT 0,
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_pedido_canal CHECK (canal_pedido IN ('APP', 'TOTEM', 'BALCAO', 'PICKUP', 'WEB')),
    CONSTRAINT ck_pedido_modalidade CHECK (modalidade_atendimento IN ('RETIRADA', 'CONSUMO_LOCAL')),
    CONSTRAINT ck_pedido_status CHECK (status IN ('AGUARDANDO_PAGAMENTO', 'EM_PREPARO', 'PRONTO', 'ENTREGUE', 'PAGAMENTO_RECUSADO', 'PAGAMENTO_FALHOU', 'CANCELADO')),
    CONSTRAINT ck_pedido_forma_pagamento CHECK (forma_pagamento = 'MOCK'),
    CONSTRAINT ck_pedido_total CHECK (total >= 0)
);

CREATE TABLE item_pedido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT NOT NULL REFERENCES pedido (id),
    produto_id BIGINT NOT NULL REFERENCES produto (id),
    quantidade INTEGER NOT NULL,
    preco_unitario NUMERIC(12, 2) NOT NULL,
    subtotal NUMERIC(12, 2) NOT NULL,
    CONSTRAINT uq_item_pedido_produto UNIQUE (pedido_id, produto_id),
    CONSTRAINT ck_item_pedido_valores CHECK (
        quantidade > 0 AND preco_unitario >= 0 AND subtotal = quantidade * preco_unitario
    )
);

CREATE TABLE pagamento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT NOT NULL UNIQUE REFERENCES pedido (id),
    chave_idempotencia UUID NOT NULL UNIQUE,
    status VARCHAR(20) NOT NULL,
    valor NUMERIC(12, 2) NOT NULL,
    codigo_mock VARCHAR(40),
    cenario_mock VARCHAR(20) NOT NULL,
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    respondido_em TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ck_pagamento_status CHECK (status IN ('APROVADO', 'RECUSADO', 'FALHA_TECNICA')),
    CONSTRAINT ck_pagamento_cenario CHECK (cenario_mock IN ('APROVAR', 'RECUSAR', 'FALHA_TECNICA')),
    CONSTRAINT ck_pagamento_valor CHECK (valor >= 0)
);

CREATE TABLE movimento_estoque (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unidade_id BIGINT NOT NULL,
    produto_id BIGINT NOT NULL,
    pedido_id BIGINT REFERENCES pedido (id),
    ator_id BIGINT REFERENCES usuario (id),
    tipo VARCHAR(20) NOT NULL,
    quantidade INTEGER NOT NULL,
    motivo VARCHAR(200),
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (unidade_id, produto_id) REFERENCES estoque_saldo (unidade_id, produto_id),
    CONSTRAINT ck_movimento_tipo CHECK (tipo IN ('ENTRADA', 'SAIDA_AJUSTE', 'RESERVA', 'LIBERACAO', 'BAIXA')),
    CONSTRAINT ck_movimento_quantidade CHECK (quantidade > 0)
);

CREATE TABLE auditoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT REFERENCES pedido (id),
    ator_id BIGINT REFERENCES usuario (id),
    acao VARCHAR(60) NOT NULL,
    resultado VARCHAR(40) NOT NULL,
    request_id UUID,
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX ix_pedido_unidade_criado ON pedido (unidade_id, criado_em DESC, id DESC);
CREATE INDEX ix_pedido_canal_status_criado ON pedido (canal_pedido, status, criado_em DESC, id DESC);
CREATE INDEX ix_movimento_saldo_criado ON movimento_estoque (unidade_id, produto_id, criado_em DESC);
