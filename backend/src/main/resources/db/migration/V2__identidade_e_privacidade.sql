ALTER TABLE usuario DROP CONSTRAINT ck_usuario_perfil;
ALTER TABLE usuario ADD CONSTRAINT ck_usuario_perfil
    CHECK (perfil IN ('CLIENTE', 'TOTEM', 'ATENDENTE', 'COZINHA', 'GERENTE', 'ADMIN'));

ALTER TABLE usuario DROP CONSTRAINT ck_usuario_unidade;
ALTER TABLE usuario ADD CONSTRAINT ck_usuario_unidade CHECK (
    (perfil IN ('CLIENTE', 'ADMIN') AND unidade_id IS NULL)
    OR (perfil IN ('TOTEM', 'ATENDENTE', 'COZINHA', 'GERENTE') AND unidade_id IS NOT NULL)
);

CREATE TABLE consentimento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuario (id),
    finalidade VARCHAR(30) NOT NULL,
    consentido BOOLEAN NOT NULL,
    versao_texto VARCHAR(30) NOT NULL,
    request_id UUID NOT NULL,
    registrado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_consentimento_finalidade CHECK (finalidade = 'FIDELIDADE')
);
CREATE INDEX ix_consentimento_usuario_finalidade ON consentimento (usuario_id, finalidade, id DESC);

